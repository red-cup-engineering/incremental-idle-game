/** Independent review regressions for exact authored-design receiving. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { cp, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { generateWorlds, projectWorlds } from '../scripts/generate-worlds.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const GENERATED = 'src/generated/world-definitions.mjs';
const digest = bytes => 'sha256:' + createHash('sha256').update(bytes).digest('hex');

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'idle-design-review-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await cp(join(ROOT, 'design'), join(root, 'design'), { recursive: true });
  await cp(join(ROOT, 'src'), join(root, 'src'), { recursive: true });
  return root;
}

test('design receipts identify the exact original UTF-8 source bytes', async t => {
  const root = await fixture(t);
  const result = await projectWorlds({ root });
  for (const source of result.design) {
    assert.equal(source.digest, digest(await readFile(join(root, source.path))));
  }
});

for (const [source, marker] of [
  ['design/world-catalog.json', 'Trace Garden'],
  ['design/world-catalog.schema.json', 'Little Worlds'],
]) {
  test(`malformed UTF-8 in ${source} refuses instead of silently changing the authored data`, async t => {
    const root = await fixture(t);
    const file = join(root, source);
    const bytes = await readFile(file);
    const index = bytes.indexOf(marker);
    assert.notEqual(index, -1);
    // This byte is inside an otherwise ordinary JSON string. A permissive
    // UTF-8 decoder substitutes U+FFFD and lets JSON.parse admit different data.
    bytes[index] = 0xff;
    await writeFile(file, bytes);
    const previous = await readFile(join(root, GENERATED));
    await assert.rejects(generateWorlds({ root }));
    assert.deepEqual(await readFile(file), bytes);
    assert.deepEqual(await readFile(join(root, GENERATED)), previous);
  });
}

test('freshness compares generated bytes even when replacement decoding would hide a change', async t => {
  const root = await fixture(t);
  const catalogPath = join(root, 'design/world-catalog.json');
  const catalog = JSON.parse(await readFile(catalogPath, 'utf8'));
  catalog[0].label = 'Trace \uFFFD Garden';
  await writeFile(catalogPath, JSON.stringify(catalog));
  await generateWorlds({ root });
  const generatedPath = join(root, GENERATED);
  const expected = await readFile(generatedPath);
  const marker = Buffer.from('\uFFFD');
  const index = expected.indexOf(marker);
  assert.notEqual(index, -1);
  const altered = Buffer.concat([expected.subarray(0, index), Buffer.from([0xff]), expected.subarray(index + marker.length)]);
  assert.equal(altered.toString('utf8'), expected.toString('utf8'), 'the counterexample must fool permissive string comparison');
  await writeFile(generatedPath, altered);
  await assert.rejects(generateWorlds({ root, check: true }));
  assert.deepEqual(await readFile(generatedPath), altered, 'check mode must retain the mismatching bytes');
  assert.equal((await generateWorlds({ root })).changed, true);
  assert.deepEqual(await readFile(generatedPath), expected);
});
